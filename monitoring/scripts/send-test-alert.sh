#!/usr/bin/env bash
# Push a synthetic alert straight into Alertmanager to exercise the delivery leg.
#
# promtool unit tests prove the *rules* are correct; they say nothing about
# whether a notification actually leaves the host. This closes that gap.
#
#   ./send-test-alert.sh              # fire, wait, then resolve
#   ./send-test-alert.sh --no-resolve # leave it firing (expires after 5m)
set -euo pipefail

ALERTMANAGER_URL="${ALERTMANAGER_URL:-http://127.0.0.1:9493}"
resolve=1
[[ "${1:-}" == "--no-resolve" ]] && resolve=0

now="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
ends="$(date -u -d '+5 minutes' +%Y-%m-%dT%H:%M:%SZ)"

post() {
  curl -sS -f -X POST -H 'Content-Type: application/json' \
    --data "$1" "$ALERTMANAGER_URL/api/v2/alerts" >/dev/null
}

echo "firing synthetic alert at $ALERTMANAGER_URL ..."
post "$(cat <<JSON
[{
  "labels": {
    "alertname": "PaperclipAlertPipelineTest",
    "severity": "critical",
    "service": "paperclip",
    "component": "credential-broker",
    "cause": "synthetic"
  },
  "annotations": {
    "summary": "Synthetic alert verifying the Alertmanager delivery path",
    "description": "Generated by monitoring/scripts/send-test-alert.sh. If this did not reach the on-call inbox, the alerting pipeline is broken and every real alert is silent too."
  },
  "startsAt": "$now",
  "endsAt": "$ends"
}]
JSON
)"

echo "queued. Inspect routing and delivery:"
echo "  curl -s $ALERTMANAGER_URL/api/v2/alerts | python3 -m json.tool"
echo "  docker logs --tail 50 platform-alertmanager"

if (( resolve )); then
  echo
  echo "waiting 45s (group_wait is 10s for critical) before resolving ..."
  sleep 45
  post "$(cat <<JSON
[{
  "labels": {
    "alertname": "PaperclipAlertPipelineTest",
    "severity": "critical",
    "service": "paperclip",
    "component": "credential-broker",
    "cause": "synthetic"
  },
  "startsAt": "$now",
  "endsAt": "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
}]
JSON
)"
  echo "resolved. Expect a [RESOLVED] follow-up if send_resolved is working."
fi
